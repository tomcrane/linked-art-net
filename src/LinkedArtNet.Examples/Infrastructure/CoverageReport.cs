using System.Text;
using LinkedArtNet.Serialization;

namespace LinkedArtNet.Examples;

/// <summary>
/// The coverage dashboard (<c>examples/coverage.md</c>): manifest examples against catalog methods, page by page,
/// with each example's status. Written by <c>tools/ExampleManifest coverage</c>; CoverageTests keeps it current.
/// </summary>
public static class CoverageReport
{
    public enum Status { Validated, Mismatch, SiteIssue, NotCached, Missing, NotOnSite }

    public sealed record Row(string Id, Status Status, Example? Example, string? Detail);

    public static string Build(SiteManifest manifest, IReadOnlyList<Example> catalog, string cachedDir)
    {
        // One row per method, or one "missing" row when an id has no method.
        var rows = manifest.ExampleIds.ToDictionary(id => id, id => Evaluate(id, catalog, cachedDir), StringComparer.Ordinal);
        var all = rows.Values.SelectMany(r => r).ToList();
        var orphans = catalog.Where(e => !rows.ContainsKey(e.Id)).Select(e => new Row(e.Id, Status.NotOnSite, e, null)).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("# Example coverage");
        sb.AppendLine();
        var implemented = rows.Values.Count(r => r.Any(x => x.Status is not Status.Missing));
        sb.AppendLine($"{implemented} of {rows.Count} site examples implemented: {all.Count(r => r.Status is Status.Validated)} validated against the site, " +
                      $"{all.Count(r => r.Status is Status.SiteIssue)} blocked by site issues, " +
                      $"{all.Count(r => r.Status is Status.Mismatch)} mismatching, " +
                      $"{all.Count(r => r.Status is Status.Missing)} not yet implemented. " +
                      $"Manifest crawled {manifest.Crawled:yyyy-MM-dd}; generated by `dotnet run --project tools/ExampleManifest -- coverage`.");
        sb.AppendLine();
        sb.AppendLine("Status: **ok** generated JSON matches the site; **site issue** expected mismatch, see the reason; **mismatch** differs and is not explained; " +
                      "**not cached** no site JSON in examples/cached (run `fetch`); **missing** no C# method yet.");

        foreach (var page in manifest.Pages.Where(p => p.Examples.Count > 0))
        {
            var done = page.Examples.Count(e => rows[e.Id].Any(r => r.Status is not Status.Missing));
            sb.AppendLine();
            sb.AppendLine($"## [{page.Title}]({page.Url}) ({done}/{page.Examples.Count})");
            sb.AppendLine();
            sb.AppendLine("| Example | Status | C# | Detail |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var e in page.Examples)
            {
                foreach (var row in rows[e.Id])
                {
                    var method = row.Example is null ? "" : $"`{row.Example.Key}`";
                    sb.AppendLine($"| [{e.Id}]({Example.SiteRoot}{e.Id}) | {Label(row.Status)} | {method} | {Escape(row.Detail ?? e.Description ?? "")} |");
                }
            }
        }

        if (orphans.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Not on the site");
            sb.AppendLine();
            sb.AppendLine("Methods whose id is not in the manifest: either the site dropped the example or the id is wrong.");
            sb.AppendLine();
            foreach (var o in orphans) sb.AppendLine($"- {o.Id} (`{o.Example!.Key}`)");
        }
        return sb.ToString();
    }

    public static IReadOnlyList<Row> Evaluate(string id, IReadOnlyList<Example> catalog, string cachedDir)
    {
        var examples = catalog.Where(e => e.Id == id).OrderBy(e => e.SiteIssue is null ? 0 : 1).ToList();
        if (examples.Count == 0) return [new Row(id, Status.Missing, null, null)];
        return examples.Select(e => Evaluate(e, cachedDir)).ToList();
    }

    public static Row Evaluate(Example example, string cachedDir)
    {
        var cached = Path.Combine(cachedDir, example.Id.Replace('/', Path.DirectorySeparatorChar) + ".json");
        if (!File.Exists(cached)) return new Row(example.Id, Status.NotCached, example, null);

        string? difference;
        try
        {
            difference = JsonEquivalence.FirstDifference(File.ReadAllText(cached), LinkedArtJson.Serialize(example.Build()));
        }
        catch (Exception ex)
        {
            difference = ex.GetType().Name + ": " + ex.Message;
        }

        if (example.SiteIssue is { } issue)
        {
            var link = issue.Url is null ? "" : $" ([issue]({issue.Url}))";
            return new Row(example.Id, Status.SiteIssue, example, issue.Reason + link + (difference is null ? " (now matches: remove the SiteIssue)" : ""));
        }
        return difference is null ? new Row(example.Id, Status.Validated, example, null) : new Row(example.Id, Status.Mismatch, example, difference);
    }

    private static string Label(Status status) => status switch
    {
        Status.Validated => "ok",
        Status.Mismatch => "**mismatch**",
        Status.SiteIssue => "site issue",
        Status.NotCached => "not cached",
        Status.Missing => "missing",
        Status.NotOnSite => "not on site",
        _ => status.ToString(),
    };

    private static string Escape(string text) => text.Replace("|", "\\|").Replace("\r", "").Replace("\n", " ");
}
